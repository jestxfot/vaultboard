export function HelpDialog(props: { onClose: () => void; onBench: (count: number) => void }) {
  return (
    <div class="quick-back" onPointerDown={() => props.onClose()}>
      <div class="dialog help" onPointerDown={(e) => e.stopPropagation()}>
        <div class="dialog-title">
          Горячие клавиши
          <button class="doc-btn" onClick={() => props.onClose()}>×</button>
        </div>
        <div class="help-grid">
          <For each={GROUPS}>
            {(g) => (
              <section>
                <h4>{g.title}</h4>
                <For each={g.rows}>
                  {([key, what]) => (
                    <div class="help-row">
                      <kbd>{key}</kbd>
                      <span>{what}</span>
                    </div>
                  )}
                </For>
              </section>
            )}
          </For>
        </div>
        <div class="help-bench">
          Замер скорости (для проверки):
          <For each={[1000, 5000, 20000]}>{(n) => <button onClick={() => { props.onClose(); props.onBench(n); }}>{n}</button>}</For>
        </div>
      </div>
    </div>
  );
}
